class SslTrustTest : public ::testing::Test
{
  protected:
    void SetUp() override
    {
        settings = lcb_settings_new();
        lcb_STATUS rc = LCB_SUCCESS;
        sctx = lcbio_ssl_new(nullptr, nullptr, nullptr, nullptr, 0, 0, &rc, settings);
        ASSERT_NE(nullptr, sctx) << lcb_strerror_short(rc);
        ERR_clear_error();
    }

    void TearDown() override
    {
        if (sctx != nullptr) {
            lcbio_ssl_free(sctx);
        }
        lcb_settings_unref(settings);
    }

    lcb_settings *settings{nullptr};
    lcbio_pSSLCTX sctx{nullptr};
};

TEST_F(SslTrustTest, AddsDerCertificate)
{
    EXPECT_EQ(1, lcbio_ssl_add_der_cert(sctx, TEST_DER_CERT, sizeof(TEST_DER_CERT)));
}

TEST_F(SslTrustTest, DuplicateLeavesErrorQueueClean)
{
    ASSERT_EQ(1, lcbio_ssl_add_der_cert(sctx, TEST_DER_CERT, sizeof(TEST_DER_CERT)));
    lcbio_ssl_add_der_cert(sctx, TEST_DER_CERT, sizeof(TEST_DER_CERT));
    EXPECT_EQ(0UL, ERR_peek_error());
}

TEST_F(SslTrustTest, RejectsMalformedDer)
{
    static const unsigned char garbage[] = {0xde, 0xad, 0xbe, 0xef, 0x00, 0x01};
    EXPECT_EQ(0, lcbio_ssl_add_der_cert(sctx, garbage, sizeof(garbage)));
    EXPECT_EQ(0UL, ERR_peek_error());
}

TEST_F(SslTrustTest, RejectsInvalidArguments)
{
    EXPECT_EQ(0, lcbio_ssl_add_der_cert(nullptr, TEST_DER_CERT, sizeof(TEST_DER_CERT)));
    EXPECT_EQ(0, lcbio_ssl_add_der_cert(sctx, nullptr, 10));
    EXPECT_EQ(0, lcbio_ssl_add_der_cert(sctx, TEST_DER_CERT, 0));
}

